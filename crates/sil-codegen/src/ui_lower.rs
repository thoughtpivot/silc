//! Lower validated Silc `UiView` trees to compiler-owned React/TSX.

use sil_core::{ExecutableGraph, PortalKind, UiNode, UiValue, UiView};

/// Rendering context: chat portals get conversation state and `/complete`;
/// everything else gets the feedback submit flow and `/submit`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Mode {
    Feedback,
    Chat,
}

pub fn render_view_app(view: &UiView, graph: &ExecutableGraph) -> String {
    match graph.portal_kind {
        PortalKind::LlmChat => render_chat_app(view),
        _ => render_feedback_app(view),
    }
}

fn render_feedback_app(view: &UiView) -> String {
    let fields = view.root.field_bindings();
    let state_decls = fields
        .iter()
        .map(|field| {
            let ident = js_ident(field);
            format!(
                "  const [{ident}, set{}] = React.useState(\"\");",
                pascal(&ident)
            )
        })
        .collect::<Vec<_>>()
        .join("\n");
    let body_fields = fields
        .iter()
        .map(|field| {
            let ident = js_ident(field);
            format!("        {ident}")
        })
        .collect::<Vec<_>>()
        .join(",\n");
    let tree = render_node(&view.root, 6, Mode::Feedback);

    format!(
        r#"// AUTO-GENERATED BY silc — DO NOT EDIT
// View: {view_name}
import * as React from "react";
import {{ AppBar }} from "./components/ui/app-bar";
import {{ Button }} from "./components/ui/button";
import {{ Card }} from "./components/ui/card";
import {{ Input }} from "./components/ui/input";
import {{ Label }} from "./components/ui/label";
import {{ NavItem }} from "./components/ui/nav-item";
import {{ RadioGroup }} from "./components/ui/radio-group";
import {{ SidePanel }} from "./components/ui/side-panel";
import {{ Textarea }} from "./components/ui/textarea";
import {{ Toolbar }} from "./components/ui/toolbar";

export function App() {{
{state_decls}
  const [status, setStatus] = React.useState("");
  const [statusKind, setStatusKind] = React.useState<"ok" | "error" | "">("");
  const [result, setResult] = React.useState("");
  const [submitting, setSubmitting] = React.useState(false);

  async function onSubmit(event: React.FormEvent<HTMLFormElement>) {{
    event.preventDefault();
    setSubmitting(true);
    setStatus("Submitting…");
    setStatusKind("");
    setResult("");
    try {{
      const response = await fetch("/submit", {{
        method: "POST",
        headers: {{ "content-type": "application/json" }},
        body: JSON.stringify({{
{body_fields}
        }}),
      }});
      const body = await response.json();
      setResult(JSON.stringify(body, null, 2));
      if (response.ok && body.ok) {{
        setStatus("Saved through Bun → Python → Go/SQLite");
        setStatusKind("ok");
      }} else {{
        setStatus(body.error || "Request failed");
        setStatusKind("error");
      }}
    }} catch (error) {{
      setStatus(String(error));
      setStatusKind("error");
    }} finally {{
      setSubmitting(false);
    }}
  }}

  return (
{tree}
  );
}}
"#,
        view_name = view.name,
        state_decls = if state_decls.is_empty() {
            "  // no bound fields".to_string()
        } else {
            state_decls
        },
        body_fields = body_fields,
        tree = tree,
    )
}

fn render_chat_app(view: &UiView) -> String {
    let fields = view.root.field_bindings();
    let field = fields
        .first()
        .map(|field| js_ident(field))
        .unwrap_or_else(|| "prompt".into());
    let setter = pascal(&field);
    let tree = render_node(&view.root, 6, Mode::Chat);

    format!(
        r#"// AUTO-GENERATED BY silc — DO NOT EDIT
// View: {view_name}
import * as React from "react";
import {{ AppBar }} from "./components/ui/app-bar";
import {{ Button }} from "./components/ui/button";
import {{ Card }} from "./components/ui/card";
import {{ ChatComposer }} from "./components/ui/chat-composer";
import {{ ChatThread, type ChatMessage }} from "./components/ui/chat-thread";
import {{ HistoryPanel }} from "./components/ui/history-panel";
import {{ Input }} from "./components/ui/input";
import {{ Label }} from "./components/ui/label";
import {{ NavItem }} from "./components/ui/nav-item";
import {{ RadioGroup }} from "./components/ui/radio-group";
import {{ SidePanel }} from "./components/ui/side-panel";
import {{ Textarea }} from "./components/ui/textarea";
import {{ Toolbar }} from "./components/ui/toolbar";

export function App() {{
  const [{field}, set{setter}] = React.useState("");
  const [history, setHistory] = React.useState<ChatMessage[]>([]);
  const [error, setError] = React.useState("");
  const [submitting, setSubmitting] = React.useState(false);

  React.useEffect(() => {{
    const controller = new AbortController();
    fetch("/history", {{ signal: controller.signal, cache: "no-store" }})
      .then(async (response) => {{
        const body = await response.json();
        if (!response.ok || !body.ok) {{
          throw new Error(body.error || "History request failed");
        }}
        setHistory(Array.isArray(body.turns) ? body.turns : []);
      }})
      .catch((cause) => {{
        if (cause instanceof DOMException && cause.name === "AbortError") return;
        setError(cause instanceof Error ? cause.message : String(cause));
      }});
    return () => controller.abort();
  }}, []);

  async function onSubmit(event: React.FormEvent<HTMLFormElement>) {{
    event.preventDefault();
    const text = {field}.trim();
    if (!text || submitting) return;
    setSubmitting(true);
    setError("");
    try {{
      const response = await fetch("/complete", {{
        method: "POST",
        headers: {{ "content-type": "application/json" }},
        body: JSON.stringify({{ {field}: text }}),
      }});
      const body = await response.json();
      if (!response.ok || !body.ok) {{
        throw new Error(body.error || "Completion failed");
      }}
      setHistory((turns) => [
        ...turns,
        {{ prompt: text, reply: body.reply || "", model: body.model || "" }},
      ]);
      set{setter}("");
    }} catch (cause) {{
      setError(cause instanceof Error ? cause.message : String(cause));
    }} finally {{
      setSubmitting(false);
    }}
  }}

  return (
{tree}
  );
}}
"#,
        view_name = view.name,
        field = field,
        setter = setter,
        tree = tree,
    )
}

fn render_node(node: &UiNode, indent: usize, mode: Mode) -> String {
    let pad = " ".repeat(indent);
    match node.component.as_str() {
        "page" => {
            let app_bar = node
                .slots
                .iter()
                .find(|(name, _)| name == "app_bar")
                .map(|(_, child)| render_node(child, indent + 2, mode))
                .unwrap_or_default();
            let side = node
                .slots
                .iter()
                .find(|(name, _)| name == "side_panel")
                .map(|(_, child)| render_node(child, indent + 4, mode))
                .unwrap_or_default();
            let body = node
                .children
                .iter()
                .map(|child| render_node(child, indent + 6, mode))
                .collect::<Vec<_>>()
                .join("\n");
            let side_block = if side.is_empty() {
                String::new()
            } else {
                format!("{side}\n")
            };
            match mode {
                Mode::Chat => format!(
                    "{pad}<div className=\"flex h-screen w-full flex-col bg-transparent\">\n{app_bar}\n{pad}  <div className=\"flex min-h-0 flex-1\">\n{side_block}{pad}    <main className=\"flex min-h-0 flex-1 flex-col gap-4 p-6\">\n{body}\n{pad}      {{error ? (\n{pad}        <p className=\"m-0 text-sm text-destructive\">{{error}}</p>\n{pad}      ) : null}}\n{pad}    </main>\n{pad}  </div>\n{pad}</div>"
                ),
                Mode::Feedback => format!(
                    "{pad}<div className=\"flex min-h-screen w-full flex-col bg-transparent\">\n{app_bar}\n{pad}  <div className=\"flex min-h-0 flex-1\">\n{side_block}{pad}    <main className=\"flex-1 p-6\">\n{body}\n{pad}      {{result ? (\n{pad}        <pre className=\"mt-5 overflow-x-auto whitespace-pre-wrap rounded-lg border border-border bg-background/55 p-4 font-mono text-sm text-muted-foreground\">\n{pad}          {{result}}\n{pad}        </pre>\n{pad}      ) : null}}\n{pad}      {{status ? (\n{pad}        <p className={{statusKind === \"error\" ? \"mt-3 text-sm text-destructive\" : statusKind === \"ok\" ? \"mt-3 text-sm text-emerald-400\" : \"mt-3 text-sm text-muted-foreground\"}}>\n{pad}          {{status}}\n{pad}        </p>\n{pad}      ) : null}}\n{pad}    </main>\n{pad}  </div>\n{pad}</div>"
                ),
            }
        }
        "app_bar" => {
            let title = escape_js_string(string_prop(node, "title").unwrap_or("Silc"));
            format!("{pad}<AppBar title=\"{title}\" />")
        }
        "side_panel" => {
            let children = render_children(node, indent + 2, mode);
            format!("{pad}<SidePanel>\n{children}\n{pad}</SidePanel>")
        }
        "nav_item" => {
            let label = escape_js_string(string_prop(node, "label").unwrap_or("Item"));
            let active = if node.has_flag("active") {
                " active"
            } else {
                ""
            };
            format!("{pad}<NavItem label=\"{label}\"{active} />")
        }
        "form" => {
            let children = node
                .children
                .iter()
                .map(|child| render_node(child, indent + 2, mode))
                .collect::<Vec<_>>()
                .join("\n");
            format!(
                "{pad}<form className=\"grid max-w-2xl gap-4\" onSubmit={{onSubmit}}>\n{children}\n{pad}</form>"
            )
        }
        "stack" => wrap_div(node, indent, mode, "grid gap-4"),
        "row" => match mode {
            Mode::Chat => wrap_div(
                node,
                indent,
                mode,
                "flex min-h-0 flex-1 items-stretch gap-4",
            ),
            Mode::Feedback => wrap_div(node, indent, mode, "flex flex-wrap items-start gap-4"),
        },
        "grid" => wrap_div(node, indent, mode, "grid gap-4 sm:grid-cols-2"),
        "card" => {
            let children = render_children(node, indent + 2, mode);
            format!("{pad}<Card>\n{children}\n{pad}</Card>")
        }
        "heading" => {
            let text = escape_js_string(string_prop(node, "text").unwrap_or(""));
            let level = node
                .prop("level")
                .and_then(|v| v.as_str())
                .unwrap_or("2")
                .trim_start_matches('h');
            let tag = match level {
                "1" => "h1",
                "3" => "h3",
                _ => "h2",
            };
            let class = match tag {
                "h1" => "m-0 text-3xl font-semibold tracking-tight",
                "h3" => "m-0 text-lg font-semibold tracking-tight",
                _ => "m-0 text-2xl font-semibold tracking-tight",
            };
            format!("{pad}<{tag} className=\"{class}\">{text}</{tag}>")
        }
        "text" => {
            let text = escape_js_string(string_prop(node, "text").unwrap_or(""));
            format!("{pad}<p className=\"m-0 text-muted-foreground\">{text}</p>")
        }
        "text_input" => {
            let field = js_ident(ident_prop(node, "field").unwrap_or("field"));
            let label = string_prop(node, "label").unwrap_or(field.as_str());
            let label_esc = escape_js_string(label);
            format!(
                "{pad}<div className=\"grid gap-2\">\n{pad}  <Label htmlFor=\"{field}\">{label_esc}</Label>\n{pad}  <Input id=\"{field}\" value={{{field}}} onChange={{(event) => set{}(event.target.value)}} />\n{pad}</div>",
                pascal(&field)
            )
        }
        "textarea" => {
            let field = js_ident(ident_prop(node, "field").unwrap_or("field"));
            let label = string_prop(node, "label").unwrap_or(field.as_str());
            let label_esc = escape_js_string(label);
            format!(
                "{pad}<div className=\"grid gap-2\">\n{pad}  <Label htmlFor=\"{field}\">{label_esc}</Label>\n{pad}  <Textarea id=\"{field}\" value={{{field}}} onChange={{(event) => set{}(event.target.value)}} rows={{8}} />\n{pad}</div>",
                pascal(&field)
            )
        }
        "radio_group" => {
            let field = js_ident(ident_prop(node, "field").unwrap_or("field"));
            let label = string_prop(node, "label");
            let label_attr = label
                .map(|l| format!(" label=\"{}\"", escape_js_string(l)))
                .unwrap_or_default();
            let options = node
                .prop("options")
                .and_then(|v| v.as_string_list())
                .map(|items| {
                    items
                        .iter()
                        .map(|item| format!("\"{}\"", escape_js_string(item)))
                        .collect::<Vec<_>>()
                        .join(", ")
                })
                .unwrap_or_default();
            format!(
                "{pad}<RadioGroup name=\"{field}\" value={{{field}}} options={{[{options}]}} onChange={{set{}}}{label_attr} />",
                pascal(&field)
            )
        }
        "toolbar" => {
            let children = render_children(node, indent + 2, mode);
            format!("{pad}<Toolbar>\n{children}\n{pad}</Toolbar>")
        }
        "button" => {
            let label = escape_js_string(string_prop(node, "label").unwrap_or("Button"));
            let variant = node
                .prop("variant")
                .and_then(|v| v.as_str())
                .unwrap_or("primary");
            let size = node.prop("size").and_then(|v| v.as_str()).unwrap_or("md");
            let submit = node.has_flag("submit");
            let type_attr = if submit { "submit" } else { "button" };
            let disabled = if submit { " disabled={submitting}" } else { "" };
            let children = if submit {
                format!("{{submitting ? \"Submitting…\" : \"{label}\"}}")
            } else {
                label
            };
            format!(
                "{pad}<Button type=\"{type_attr}\" variant=\"{variant}\" size=\"{size}\"{disabled}>{children}</Button>"
            )
        }
        "chat" => {
            let field = js_ident(ident_prop(node, "field").unwrap_or("prompt"));
            let label_attr = string_prop(node, "label")
                .map(|l| format!(" label=\"{}\"", escape_js_string(l)))
                .unwrap_or_default();
            let placeholder_attr = string_prop(node, "placeholder")
                .map(|p| format!(" placeholder=\"{}\"", escape_js_string(p)))
                .unwrap_or_default();
            format!(
                "{pad}<section className=\"flex min-h-0 flex-1 flex-col gap-4\">\n{pad}  <ChatThread messages={{history}} thinking={{submitting}} />\n{pad}  <ChatComposer id=\"{field}\" value={{{field}}} onChange={{set{}}} onSubmit={{onSubmit}} submitting={{submitting}}{label_attr}{placeholder_attr} />\n{pad}</section>",
                pascal(&field)
            )
        }
        "chat_history" => {
            let title_attr = string_prop(node, "title")
                .map(|t| format!(" title=\"{}\"", escape_js_string(t)))
                .unwrap_or_default();
            let collapsible_attr = if node.has_flag("collapsible") {
                " collapsible"
            } else {
                ""
            };
            format!("{pad}<HistoryPanel items={{history}}{title_attr}{collapsible_attr} />")
        }
        other => format!("{pad}{{/* unsupported ui::{other} */}}"),
    }
}

fn wrap_div(node: &UiNode, indent: usize, mode: Mode, class_name: &str) -> String {
    let pad = " ".repeat(indent);
    let children = render_children(node, indent + 2, mode);
    format!("{pad}<div className=\"{class_name}\">\n{children}\n{pad}</div>")
}

fn render_children(node: &UiNode, indent: usize, mode: Mode) -> String {
    node.children
        .iter()
        .map(|child| render_node(child, indent, mode))
        .collect::<Vec<_>>()
        .join("\n")
}

fn string_prop<'a>(node: &'a UiNode, name: &str) -> Option<&'a str> {
    node.prop(name).and_then(|value| match value {
        UiValue::String(s) => Some(s.as_str()),
        _ => None,
    })
}

fn ident_prop<'a>(node: &'a UiNode, name: &str) -> Option<&'a str> {
    node.prop(name).and_then(|value| match value {
        UiValue::Ident(s) => Some(s.as_str()),
        _ => None,
    })
}

fn js_ident(raw: &str) -> String {
    let mut out = String::new();
    for (index, ch) in raw.chars().enumerate() {
        if ch.is_ascii_alphanumeric() || ch == '_' {
            if index == 0 && ch.is_ascii_digit() {
                out.push('_');
            }
            out.push(ch);
        } else {
            out.push('_');
        }
    }
    if out.is_empty() {
        "_field".into()
    } else {
        out
    }
}

fn pascal(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
        None => String::new(),
    }
}

fn escape_js_string(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
}

#[cfg(test)]
mod tests {
    use super::*;
    use sil_core::{ExecutionMode, PortalKind, Span, UiSurface};

    fn sample_graph() -> ExecutableGraph {
        ExecutableGraph {
            mode: ExecutionMode::Runnable,
            portal_kind: PortalKind::Feedback,
            service: "WebPortal".into(),
            processor: "TextAnalyzer".into(),
            sink: "FeedbackDb".into(),
            http_port: 18088,
            http_route: "/".into(),
            sqlite_table: "feedback".into(),
            ui_surface: Some(UiSurface::Web),
            terminal_port: None,
            api_routes: vec![],
            model_ref: None,
            ui_view: None,
            ui_contract: Some("FeedbackRecord".into()),
        }
    }

    #[test]
    fn lowers_page_with_bindings() {
        let view = UiView {
            name: "FeedbackView".into(),
            root: UiNode {
                component: "page".into(),
                props: vec![],
                slots: vec![(
                    "app_bar".into(),
                    UiNode {
                        component: "app_bar".into(),
                        props: vec![("title".into(), UiValue::String("Feedback".into()))],
                        slots: vec![],
                        children: vec![],
                        span: Span::default(),
                    },
                )],
                children: vec![UiNode {
                    component: "form".into(),
                    props: vec![],
                    slots: vec![],
                    children: vec![
                        UiNode {
                            component: "text_input".into(),
                            props: vec![
                                ("field".into(), UiValue::Ident("author".into())),
                                ("label".into(), UiValue::String("Author".into())),
                            ],
                            slots: vec![],
                            children: vec![],
                            span: Span::default(),
                        },
                        UiNode {
                            component: "button".into(),
                            props: vec![
                                ("label".into(), UiValue::String("Submit".into())),
                                ("submit".into(), UiValue::Flag),
                            ],
                            slots: vec![],
                            children: vec![],
                            span: Span::default(),
                        },
                    ],
                    span: Span::default(),
                }],
                span: Span::default(),
            },
            span: Span::default(),
        };
        let tsx = render_view_app(&view, &sample_graph());
        assert!(tsx.contains("AppBar"));
        assert!(tsx.contains("/submit"));
        assert!(tsx.contains("setAuthor"));
        assert!(tsx.contains("author"));
        assert!(!tsx.contains("<script"));
    }
}
