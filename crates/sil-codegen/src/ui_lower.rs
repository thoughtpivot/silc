fn render_terminal_router(app: &App) -> String {
    let mut cases = String::new();
    for (i, route) in app.routes.iter().enumerate() {
        let keyword = if i == 0 { "if" } else { "else if" };
        cases.push_str(&format!(
            "  {keyword} (path === {path}) page = <{comp} />;\n",
            keyword = keyword,
            path = escape_js_string(&route.path),
            comp = route.component
        ));
    }
    let default = app
        .routes
        .first()
        .map(|r| r.component.clone())
        .unwrap_or_else(|| "Stack".into());
    format!(
        r#"export function App() {{
  const [path, setPath] = useState({home});
  useEffect(() => {{
    __silcNavigateImpl = setPath;
  }}, []);
  let page = <{default} />;
{cases}  return page;
}}
"#,
        home = escape_js_string(
            &app.routes
                .first()
                .map(|r| r.path.clone())
                .unwrap_or_else(|| "/".into())
        ),
        cases = cases,
        default = default
    )
}

fn escape_js_string(s: &str) -> String {
    format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\""))
}

fn pascal(s: &str) -> String {
    let mut out = String::new();
    let mut cap = true;
    for ch in s.chars() {
        if ch == '_' || ch == '-' {
            cap = true;
            continue;
        }
        if cap {
            out.extend(ch.to_uppercase());
            cap = false;
        } else {
            out.push(ch);
        }
    }
    out
}

fn snake_case(s: &str) -> String {
    let mut out = String::new();
    for (i, ch) in s.chars().enumerate() {
        if ch.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

